export function mapCatalogRow(row: Record<string, any>): CatalogCar {
  const brand = String(row.brand || '');
  const model = String(row.model || '');
  return {
    id: String(row.id),
    brand,
    model,
    category: String(row.category || 'Économique'),
    seats: Number(row.seats ?? 5),
    default_fuel: (row.default_fuel as FuelType) || 'diesel',
    default_transmission: (row.default_transmission as TransmissionType) || 'manual',
    image_url: resolveCatalogImage(brand, model, row.image_url),
    created_at: row.created_at ? String(row.created_at) : undefined,
  };
}

